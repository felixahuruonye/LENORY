import type { ToolContext, ToolResult, Citation, ArtifactRef } from "../types";
import { generateFile, randomArtifactId } from "../fileFactory";
import { storage } from "../../storage";

async function uploadArtifact(
  userId: string,
  folderId: string | null,
  file: { buffer: Buffer; mimeType: string; fileName: string },
  label: string
): Promise<ArtifactRef | null> {
  try {
    // Prefer dedicated media upload helper path via dynamic import of kb routes logic
    const { supabaseDb } = await import("../../db");
    if (!supabaseDb) return null;
    const bucket = "lenory-kb-media";
    try {
      await supabaseDb.storage.createBucket(bucket, { public: true, fileSizeLimit: 80 * 1024 * 1024 });
    } catch {}
    const pathKey = `${userId}/assistant/${Date.now()}-${file.fileName.replace(/[^\w.\-]+/g, "_")}`;
    const { error } = await supabaseDb.storage
      .from(bucket)
      .upload(pathKey, file.buffer, { contentType: file.mimeType, upsert: false });
    if (error) {
      console.error("[assistant] storage upload:", error.message);
      return null;
    }
    const { data } = supabaseDb.storage.from(bucket).getPublicUrl(pathKey);
    const url = data?.publicUrl;
    if (!url) return null;

    if (folderId) {
      try {
        await storage.createKBFile({
          folder_id: folderId,
          user_id: userId,
          name: label || file.fileName,
          file_type: "assistant_artifact",
          mime_type: file.mimeType,
          file_size: file.buffer.length,
          full_text_url: url,
          source_type: "assistant_file",
          extracted_text: `Generated by LENORY assistant: ${file.fileName}`,
        });
      } catch (e) {
        console.warn("[assistant] kb file meta save failed", e);
      }
    }

    return {
      id: randomArtifactId(),
      name: file.fileName,
      mimeType: file.mimeType,
      format: file.fileName.split(".").pop() || "bin",
      size: file.buffer.length,
      url,
      createdAt: new Date().toISOString(),
    };
  } catch (e: any) {
    console.error("[assistant] uploadArtifact", e?.message);
    return null;
  }
}

export async function toolWebSearch(ctx: ToolContext, query: string): Promise<ToolResult> {
  ctx.onStatus?.("searching", query);
  try {
    const { searchInternetWithGemini } = await import("../../gemini");
    const data = await searchInternetWithGemini(query);
    const results = data?.results || data?.items || [];
    const citations: Citation[] = (results || []).slice(0, 8).map((r: any) => ({
      title: r.title || "Source",
      url: r.link || r.url || "",
      snippet: r.snippet || r.content || "",
    })).filter((c: Citation) => c.url);
    const answer = data?.answer || "";
    const summary =
      (answer ? `Answer: ${answer}\n\n` : "") +
      citations.map((c, i) => `${i + 1}. ${c.title} — ${c.url}\n   ${c.snippet || ""}`).join("\n");
    return {
      tool: "web_search",
      success: citations.length > 0 || !!answer,
      summary: summary || "No results found.",
      data: { answer, results: citations },
      citations,
    };
  } catch (e: any) {
    return { tool: "web_search", success: false, summary: "Search failed", error: e?.message || String(e) };
  }
}

export async function toolListKbFolders(ctx: ToolContext): Promise<ToolResult> {
  ctx.onStatus?.("reading_files", "Listing notebooks");
  try {
    const folders = await storage.getKBFolders(ctx.userId);
    const list = (folders || []).map((f: any) => ({
      id: f.id,
      name: f.name,
      description: f.description,
    }));
    return {
      tool: "kb_list_folders",
      success: true,
      summary: list.length
        ? list.map((f: any) => `- ${f.name} (${f.id})`).join("\n")
        : "No Knowledge Base folders found.",
      data: { folders: list },
    };
  } catch (e: any) {
    return { tool: "kb_list_folders", success: false, summary: "Failed to list folders", error: e?.message };
  }
}

export async function toolReadKbFolder(ctx: ToolContext, folderId: string): Promise<ToolResult> {
  ctx.onStatus?.("reading_files", folderId);
  try {
    const folders = await storage.getKBFolders(ctx.userId);
    const folder = (folders || []).find((f: any) => f.id === folderId);
    if (!folder) {
      return {
        tool: "kb_read_folder",
        success: false,
        summary: "Folder not found or not owned by you.",
        error: "FORBIDDEN",
      };
    }
    const files = await storage.getKBFiles(folderId);
    const materials = (files || [])
      .map((f: any) => `--- ${f.name} ---\n${String(f.extracted_text || "").slice(0, 4000)}`)
      .join("\n\n")
      .slice(0, 14000);
    return {
      tool: "kb_read_folder",
      success: true,
      summary: materials || "Folder is empty.",
      data: { folderId, name: folder.name, fileCount: (files || []).length },
    };
  } catch (e: any) {
    return { tool: "kb_read_folder", success: false, summary: "Read failed", error: e?.message };
  }
}

export async function toolGenerateFile(
  ctx: ToolContext,
  args: { format: string; title?: string; content: string; fileName?: string; folderId?: string }
): Promise<ToolResult> {
  ctx.onStatus?.("generating_file", args.format);
  try {
    if (!args.content || !String(args.content).trim()) {
      return { tool: "generate_file", success: false, summary: "No content provided for file", error: "EMPTY" };
    }
    const generated = generateFile({
      format: args.format,
      title: args.title,
      content: args.content,
      fileName: args.fileName,
    });
    if (!generated.buffer?.length) {
      return { tool: "generate_file", success: false, summary: "Generator returned empty file", error: "EMPTY_BUFFER" };
    }
    ctx.onStatus?.("saving", generated.fileName);

    // Ensure user has a folder for assistant outputs
    let folderId = args.folderId || null;
    if (!folderId) {
      try {
        const folders = await storage.getKBFolders(ctx.userId);
        let dest = (folders || []).find((f: any) => /assistant|generated|lenory files/i.test(f.name || ""));
        if (!dest) {
          dest = await storage.createKBFolder({
            user_id: ctx.userId,
            name: "LENORY Generated Files",
            description: "Files created by Ask LENORY assistant",
          });
        }
        folderId = dest?.id || null;
      } catch {}
    }

    const artifact = await uploadArtifact(ctx.userId, folderId, generated, generated.fileName);
    if (!artifact) {
      // Fallback: data URL only for small text files
      if (generated.buffer.length < 200_000 && generated.mimeType.startsWith("text/")) {
        const dataUrl = `data:${generated.mimeType};base64,${generated.buffer.toString("base64")}`;
        const fallback: ArtifactRef = {
          id: randomArtifactId(),
          name: generated.fileName,
          mimeType: generated.mimeType,
          format: generated.extension,
          size: generated.buffer.length,
          url: dataUrl,
          createdAt: new Date().toISOString(),
        };
        return {
          tool: "generate_file",
          success: true,
          summary: `Created ${generated.fileName} (${generated.buffer.length} bytes). Storage bucket unavailable — using inline download.`,
          artifacts: [fallback],
          data: { fileName: generated.fileName, size: generated.buffer.length },
        };
      }
      return {
        tool: "generate_file",
        success: false,
        summary: "File was generated but could not be stored for download. Check Supabase storage.",
        error: "STORAGE_FAILED",
      };
    }
    ctx.onStatus?.("validating", artifact.name);
    return {
      tool: "generate_file",
      success: true,
      summary: `Created and stored **${artifact.name}** (${artifact.size} bytes).\nDownload: ${artifact.url}`,
      artifacts: [artifact],
      data: { fileName: artifact.name, size: artifact.size, url: artifact.url },
    };
  } catch (e: any) {
    return { tool: "generate_file", success: false, summary: "File generation failed", error: e?.message || String(e) };
  }
}
